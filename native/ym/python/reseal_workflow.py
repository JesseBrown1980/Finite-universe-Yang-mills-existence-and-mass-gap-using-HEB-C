#!/usr/bin/env python3
"""Write the seal-only re-run workflow for a failed stage B seal.

The certify script is copied verbatim from a stage B workflow regenerated by the
fixed generator (GENERATED), except:
  - the two `test needs.cell/merge.result` lines are dropped (there are no cell or
    merge jobs: this workflow computes nothing, it only re-seals);
  - RESEAL binding lines are appended to the seal before it is written.
The artifacts are fetched by artifact id, re-checked against fresh API metadata,
and verified all-or-nothing by reseal_verify.py before the certify script runs.
usage: reseal_workflow.py GENERATED MANIFEST RUN HEAD LX LY CELLS MERGES BRANCH OUT   json=0
"""
import os
import sys


def certify_block(gen):
    lines = open(gen).read().split("\n")
    i = next(k for k, l in enumerate(lines) if l.strip() == "- name: Certify and seal")
    assert lines[i + 1].strip() == "run: |"
    body = []
    for l in lines[i + 2:]:
        if l.strip() and not l.startswith("          "):
            break
        body.append(l)
    while body and not body[-1].strip():
        body.pop()
    drop = [l for l in body if "needs.cell.result" in l or "needs.merge.result" in l]
    assert len(drop) == 2, drop
    body = [l for l in body if l not in drop]
    mv = [k for k, l in enumerate(body) if l.strip().startswith("mv seal.hbp ")]
    assert len(mv) == 1
    return body, mv[0]


def main():
    gen, man, run, head, lx, ly, ncell, nmerge, branch, out = sys.argv[1:11]
    body, k = certify_block(gen)
    lat = "%sx%s" % (lx, ly)
    up = lat.upper()
    bind = [
        '          # bind the seal to everything it used',
        '          echo "RESEAL|source_run=%s|source_head=%s|workflow_commit=$GITHUB_SHA|reseal_run=$GITHUB_RUN_ID|json=0" >> seal.hbp' % (run, head),
        '          echo "RESEAL_MANIFEST|file=%s|sha256=$(sha256sum %s | cut -c1-64)|json=0" >> seal.hbp' % (man, man),
        '          echo "RESEAL_STAGE_A|sha256=$(sha256sum native/ym/results/%s_stage_a/HEBC-YM-%s-STAGE-A.hbp | cut -c1-64)|json=0" >> seal.hbp' % (lat, up),
        '          echo "RESEAL_GENERATOR|stage_b_workflow_py_sha256=$(sha256sum native/ym/python/stage_b_workflow.py | cut -c1-64)|generator_commit=$(git log -1 --format=%H -- native/ym/python/stage_b_workflow.py)|json=0" >> seal.hbp',
        '          cat reseal-verify.hbp gen-control.hbp >> seal.hbp',
        '          grep "^MANIFEST|" %s | cut -d"|" -f2-3 | sed "s/^/RESEAL_ARTIFACT|/" >> seal.hbp' % man,
    ]
    body = body[:k] + bind + body[k:]
    wf = os.path.relpath(out, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
    y = f'''# Seal-only re-run of {lat} stage B (source run {run}, head {head}).
# Generated by native/ym/python/reseal_workflow.py. It launches no cell or merge
# computation. It fetches the source run's {int(ncell) + int(nmerge)} artifacts by id, re-checks them against fresh
# API metadata and the frozen manifest, verifies size and raw-ZIP SHA-256 of all of
# them before extracting any (reseal_verify.py), then runs the certify script of the
# fixed generator verbatim. Any failure before the seal is INCONCLUSIVE. json=0
name: HEB-C YM {lat} stage B re-seal (seal-only, run {run})

on:
  push:
    branches: [{branch}]
    paths: ['{wf}']

permissions:
  contents: read
  actions: read

concurrency:
  group: hebc-ym-{lat}-stage-b-reseal
  cancel-in-progress: false

jobs:
  reseal:
    name: Verify artifacts, certify, seal (no computation)
    runs-on: ubuntu-latest
    timeout-minutes: 60
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - name: Frozen manifest and clean-root generator control
        run: |
          set -euo pipefail
          (cd $(dirname {man}) && sha256sum -c $(basename {man} .hbp).sha256)
          grep -q '^MANIFEST_TOTAL|run={run}|head={head}|artifacts={int(ncell) + int(nmerge)}|cells={ncell}|merges={nmerge}|problems=0|.*|result=PASS|' {man}
          bash native/ym/python/reseal_generator_control.sh | tee $RUNNER_TEMP/gen-control.hbp
          grep -q '^GEN_CONTROL_RESULT|result=PASS|' $RUNNER_TEMP/gen-control.hbp
          cp $RUNNER_TEMP/gen-control.hbp gen-control.hbp
      - name: Fetch artifacts by id; fresh metadata must equal the frozen manifest
        env:
          GH_TOKEN: ${{{{ github.token }}}}
        run: |
          set -euo pipefail
          R=$GITHUB_REPOSITORY
          # bounded retries on API errors (e.g. HTTP 5xx); integrity is still decided by
          # the manifest comparison and the size/digest verification, never by the fetch
          get() {{ local n=0; until gh api "$1" "${{@:2}}" > "$RUNNER_TEMP/get.out"; do n=$((n+1)); [ $n -ge 6 ] && return 1; sleep $((n*n*5)); done; cat "$RUNNER_TEMP/get.out"; }}
          for p in 1 2 3; do get "repos/$R/actions/runs/{run}/artifacts?per_page=100&page=$p" -q '.artifacts[]|[.id,.name,.size_in_bytes,.digest,.expired,.workflow_run.id,.workflow_run.head_sha]|@tsv'; done > fresh.tsv
          python3 native/ym/python/reseal_manifest.py fresh.tsv .github/workflows/hebc-ym-{lat}-stage-b-r9.yml {run} {head} {ncell} {nmerge} > fresh-manifest.hbp
          cmp fresh-manifest.hbp {man}
          mkdir zips
          for id in $(grep '^MANIFEST|' {man} | sed -E 's/.*\\|artifact_id=([0-9]+)\\|.*/\\1/'); do
            get "repos/$R/actions/artifacts/$id/zip" > zips/$id.zip
          done
          echo "RESEAL_FETCH|zips=$(ls zips | wc -l)|json=0"
      - name: Verify all artifacts before any extraction (all-or-nothing)
        run: |
          set -euo pipefail
          python3 native/ym/python/reseal_verify.py {man} zips arts {ncell} {nmerge} | tee reseal-verify.hbp
          grep -q '^RESEAL_VERIFY_TOTAL|artifacts={int(ncell) + int(nmerge)}|result=PASS|' reseal-verify.hbp
      - name: Certify and seal
        run: |
''' + "\n".join(body) + f'''
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: sealed-hebc-ym-{lat}-stage-b-reseal
          if-no-files-found: ignore
          path: |
            HEBC-YM-{up}-STAGE-B.*
            reseal-verify.hbp
            gen-control.hbp
            fresh.tsv
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: source-zips-{run}
          if-no-files-found: ignore
          retention-days: 90
          path: zips
'''
    open(out, "w").write(y)
    print("RESEAL_WORKFLOW|out=%s|certify_lines=%d|binding_lines=%d|result=PASS|json=0" % (wf, len(body), len(bind)))


if __name__ == "__main__":
    main()
