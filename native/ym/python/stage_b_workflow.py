#!/usr/bin/env python3
"""Write the stage B GitRAM workflow for one lattice from a sealed stage A
receipt, through hebc_ym_http0 only.

Inputs
  SEALED, SHA256    stage A receipt + checksum, validated by stage_b_specs.py
                    (checksum, PASS seal, exact converged clusters, k = 0..11,
                    lo <= hi, 7+1 vacuum split); this script refuses otherwise.
  LX LY             lattice
  RECEIPT_COUPLINGS the exact coupling set stage A must contain (e.g. 9,15,27,45,81)
  COUPLINGS         couplings to certify now, subset of the receipt's (e.g. 9)
  CORES             file of "spec core_rows" lines (ddcore at that threshold)
  OUT               workflow path
  [SPLIT=300] [COLS=30]  counts with core > SPLIT are split into countcols
                    cells of COLS columns, merged by a countmerge job.

Jobs in the written workflow
  cell     one backend job each (count, or countcols) from an empty root with
           HEBC_YM_FRESH=1, re-executed with verify; count cells must report
           ambiguous=0 and result=PASS.
  merge    one per split count: collects that count's countcols shard
           directories, rebuilds the sector, runs countmerge (integrity, spec,
           INPUT_MATRIX, exact column partition) and verify; must report
           ambiguous=0 and result=PASS.
  certify  integrity of every shard, shell_gap_cert.py --lattice on the
           committed stage A clusters + all counts, and for the lowest
           coupling the one-point ray E9(r)-E8(r) >= tB - 3*(2*LX*LY) for all
           r >= that coupling (monotone_cells.py --ray), then seal.
Integer-only.
usage: stage_b_workflow.py SEALED SHA256 LX LY RECEIPT_COUPLINGS COUPLINGS CORES OUT [SPLIT] [COLS]   json=0
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    sealed, sha, lx, ly, rcps, cps, cores_f, out = sys.argv[1:9]
    lx, ly = int(lx), int(ly)
    split = int(sys.argv[9]) if len(sys.argv) > 9 else 300
    cols = int(sys.argv[10]) if len(sys.argv) > 10 else 30
    want = [int(x) for x in cps.split(",")]
    res = subprocess.run([sys.executable, os.path.join(HERE, "stage_b_specs.py"), sealed, sha, str(lx), str(ly), rcps], capture_output=True, text=True)
    if res.returncode != 0:
        print(res.stdout.strip())
        print("STAGE_B_WORKFLOW|result=FAIL|reason=stage_A_receipt_rejected|json=0")
        sys.exit(2)
    specs = [s for s in res.stdout.split() if s.startswith("count/") and int(s.split("/")[6]) // 1000 in want]
    cores = {}
    for line in open(cores_f):
        if line.strip():
            k, v = line.split()
            cores[k] = int(v)
    missing = [s for s in specs if s not in cores]
    if missing:
        print("STAGE_B_WORKFLOW|result=FAIL|reason=no_core_size_for|spec=%s|json=0" % missing[0])
        sys.exit(2)
    cells, merges = [], []
    for s in specs:
        if cores[s] <= split:
            cells.append(s)
        else:
            merges.append(s)
            for a in range(0, cores[s], cols):
                cells.append("countcols/%s/%d/%d" % (s.split("/", 1)[1], a, min(a + cols, cores[s])))
    lat = "%dx%d" % (lx, ly)
    flat = 3 * 2 * lx * ly * 1000000
    rel = os.path.relpath(sealed, os.path.join(HERE, "..", "..", ".."))
    wfrel = os.path.relpath(out, os.path.join(HERE, "..", "..", ".."))
    inc = "\n".join('          - {id: "%03d", spec: "%s"}' % (i + 1, c) for i, c in enumerate(cells))
    minc = "\n".join('          - {id: "m%02d", spec: "%s"}' % (i + 1, c.replace("count/", "countmerge/", 1)) for i, c in enumerate(merges))
    if not merges:
        minc = '          - {id: "none", spec: "none"}'
    nm = len(merges)
    n = len(cells)
    y = f'''# Stage B for the {lat} finite volume at r = {cps}, generated by
# native/ym/python/stage_b_workflow.py from the sealed stage A receipt
# {rel} (accepted by stage_b_specs.py). Thresholds by the fixed rule; counts
# with core > {split} are split into countcols cells of {cols} columns and merged
# by countmerge (input integrity, spec, INPUT_MATRIX, exact column partition).
# Every count must report ambiguous=0 and result=PASS. Integer-only, json=0.
name: HEB-C YM {lat} stage B r={cps} ({n} cells, {nm} merges)

on:
  workflow_dispatch:
  push:
    branches: [http0-ym-backend-finite-volumes]
    paths: ['{wfrel}']

permissions:
  contents: read

concurrency:
  group: hebc-ym-{lat}-stage-b-${{{{ github.ref }}}}
  cancel-in-progress: false

jobs:
  cell:
    name: Cell ${{{{ matrix.id }}}} ${{{{ matrix.spec }}}}
    strategy:
      fail-fast: false
      max-parallel: 20
      matrix:
        include:
{inc}
    runs-on: ubuntu-latest
    timeout-minutes: 355
    steps:
      - uses: actions/checkout@v4
      - name: Toolchain 1.81
        run: |
          rustup toolchain install 1.81.0 --profile minimal
          rustup override set 1.81.0
      - name: Build offline from vendored sources
        working-directory: native/ym
        run: cargo build --release --offline --locked
      - name: Fresh sector + one job + verify
        working-directory: native/ym
        env:
          HEBC_YM_FRESH: "1"
        run: |
          set -euo pipefail
          B=target/release/hebc_ym_http0; R=$RUNNER_TEMP/root; spec="${{{{ matrix.spec }}}}"
          sec="sector/$(echo $spec | cut -d/ -f2-5)"; id=$(echo $spec | tr / _)
          $B job $R $sec
          $B job $R $spec | tee job.txt
          $B verify $R $spec | tee -a job.txt
          grep -q '^HEBC_YM|result=PASS|action=verify|' job.txt
          case $spec in count/*) grep -q '|ambiguous=0|result=PASS|' $R/shards/$id/run.hbp ;; esac
          mkdir -p out/shards; cp -r $R/shards/$id out/shards/
      - uses: actions/upload-artifact@v4
        with:
          name: cell-${{{{ matrix.id }}}}
          retention-days: 30
          if-no-files-found: error
          path: native/ym/out

  merge:
    name: Merge ${{{{ matrix.id }}}} ${{{{ matrix.spec }}}}
    needs: cell
    if: always()
    strategy:
      fail-fast: false
      matrix:
        include:
{minc}
    runs-on: ubuntu-latest
    timeout-minutes: 300
    steps:
      - uses: actions/checkout@v4
        if: matrix.spec != 'none'
      - uses: actions/download-artifact@v4
        if: matrix.spec != 'none'
        with:
          pattern: cell-*
          path: cells
          merge-multiple: true
      - name: Toolchain 1.81
        if: matrix.spec != 'none'
        run: |
          rustup toolchain install 1.81.0 --profile minimal
          rustup override set 1.81.0
      - name: countmerge + verify
        if: matrix.spec != 'none'
        env:
          HEBC_YM_FRESH: "1"
        run: |
          set -euo pipefail
          (cd native/ym && cargo build --release --offline --locked)
          B=native/ym/target/release/hebc_ym_http0; R=$RUNNER_TEMP/root; spec="${{{{ matrix.spec }}}}"
          cid=$(echo $spec | sed 's#^countmerge/#count/#' | tr / _); id=$(echo $spec | tr / _)
          mkdir -p $R/scol/$cid
          cp -r cells/shards/countcols_${{cid#count_}}_* $R/scol/$cid/
          $B job $R "sector/$(echo $spec | cut -d/ -f2-5)"
          $B job $R $spec | tee job.txt
          $B verify $R $spec | tee -a job.txt
          grep -q '^HEBC_YM|result=PASS|action=verify|' job.txt
          grep -q '|ambiguous=0|result=PASS|' $R/shards/$id/run.hbp
          mkdir -p out/shards; cp -r $R/shards/$id out/shards/
      - uses: actions/upload-artifact@v4
        if: matrix.spec != 'none'
        with:
          name: merge-${{{{ matrix.id }}}}
          retention-days: 30
          if-no-files-found: error
          path: out

  certify:
    name: Integrity, certificates, one-point ray, seal
    needs: [cell, merge]
    if: always()
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: actions/checkout@v4
      - uses: actions/download-artifact@v4
        with:
          path: arts
          merge-multiple: true
      - name: Certify and seal
        run: |
          set -euo pipefail
          shopt -s nullglob
          P=native/ym/python
          test "${{{{ needs.cell.result }}}}" = success
          test "${{{{ needs.merge.result }}}}" = success
          n=$(ls -d arts/shards/count_* arts/shards/countcols_* arts/shards/countmerge_* 2>/dev/null | wc -l); echo "shards=$n expected={n + nm}"
          test "$n" -eq {n + nm}
          python3 $P/verify_shard_integrity.py arts/shards | tee seal.hbp
          grep -q '|failed=0|.*|result=PASS|' seal.hbp
          (cd $(dirname {rel}) && sha256sum -c $(basename {rel}).sha256)
          grep '^SHARD|cluster_' {rel} | sed -E 's/^SHARD\\|cluster_{lx}_{ly}_(-?1)_(-?1)_1_([0-9]+)_12_4\\|CLUSTER/YM{lx}X{ly}_S\\1_\\2_r\\3_CLUSTER/' > clusters.hbp
          cat arts/shards/count_*/run.hbp arts/shards/countmerge_*/run.hbp 2>/dev/null > counts.hbp
          for r in {" ".join(map(str, want))}; do python3 $P/shell_gap_cert.py --lattice {lat} clusters.hbp $r counts.hbp; done | tee -a seal.hbp
          python3 $P/monotone_cells.py --lattice {lat} --ray {flat} seal.hbp | tee -a seal.hbp
          g=$(grep -c '^SHELL_GAP_CERT|.*|result=PASS|' seal.hbp); r=$(grep -c '^MONOTONE_CELLS|.*|result=PASS|' seal.hbp)
          if [ "$g" = {len(want)} ] && [ "$r" = 1 ]; then st=PASS; else st=FAIL; fi
          cat arts/shards/*/run.anchor >> seal.hbp
          echo "GITRAM_SEAL|lattice={lat}|couplings={cps}|gap_certs=$g/{len(want)}|ray_E8_upper={flat}/1000000|status=$st|json=0" >> seal.hbp
          mv seal.hbp HEBC-YM-{lat.upper()}-STAGE-B.hbp; sha256sum HEBC-YM-{lat.upper()}-STAGE-B.hbp > HEBC-YM-{lat.upper()}-STAGE-B.sha256
          test "$st" = PASS
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: sealed-hebc-ym-{lat}-stage-b
          retention-days: 30
          if-no-files-found: error
          path: HEBC-YM-{lat.upper()}-STAGE-B.*
'''
    open(out, "w").write(y)
    print("STAGE_B_WORKFLOW|lattice=%s|couplings=%s|counts=%d|single_cells=%d|split_counts=%d|countcols_cells=%d|out=%s|result=PASS|json=0"
          % (lat, cps, len(specs), len(specs) - nm, nm, n - (len(specs) - nm), out))


if __name__ == "__main__":
    main()
