#!/usr/bin/env python3
"""Generate .github/workflows/hebc-ym-room-identity.yml: the CI run of the identity gates
P2 (builder) and P3 (runner) of results/3x4_stream/MEMORY-PILOT-SPEC.md, as frozen in
results/3x4_stream/P2-P3-CI-SPEC.md. Integer-only, json=0.
usage: room_identity_workflow.py > .github/workflows/hebc-ym-room-identity.yml
"""

P2_LATTICES = ("2/3", "2/4", "3/3")
JE, JB, FDIG, TOL = 1000, 9000, 12, 1000
# threshold (milli-units) -> (frozen core size from ddcore, number of column chunks)
THRESHOLDS = ((60000000, 101, 2), (72000000, 1137, 16), (90000000, 2940, 40))
V1_COMMIT = "9f60d568f66aa63989def94c6a7494dd27d5b6ef"


def chunks(core, s):
    return [(i * core // s, (i + 1) * core // s) for i in range(s)]


def count_tail(t):
    return "%d/%d/%d/%d/%d" % (JE, JB, t, FDIG, TOL)


def main():
    rows = []
    for side in ("shell", "room"):
        for t, core, s in THRESHOLDS:
            for a, b in chunks(core, s):
                rows.append('          - {side: "%s", t: "%d", a: "%d", b: "%d"}' % (side, t, a, b))
    merges = []
    for side in ("shell", "room"):
        for t, core, s in THRESHOLDS:
            merges.append('          - {side: "%s", t: "%d", s: "%d", core: "%d"}' % (side, t, s, core))
    p2 = "\n".join('          - {l: "%s"}' % x for x in P2_LATTICES)
    tail = {t: count_tail(t) for t, _, _ in THRESHOLDS}
    print(TEMPLATE.format(
        p2=p2, cols="\n".join(rows), merges="\n".join(merges), v1=V1_COMMIT,
        ncols=len(rows), je=JE, jb=JB, fdig=FDIG, tol=TOL,
        t60=tail[60000000], t72=tail[72000000], t90=tail[90000000]).rstrip("\n"))


TEMPLATE = r"""# Room-backed lane identity gates in CI (MEMORY-PILOT-SPEC.md P2 and P3), frozen in
# native/ym/results/3x4_stream/P2-P3-CI-SPEC.md. Generated by
# native/ym/python/room_identity_workflow.py; do not edit by hand.
# P2: `ymroom text` equal byte for byte to `ymsec` on 2x3, 2x4, 3x3 (roomident jobs).
# P3: roomschur and shellschur on 3x3 at t = 60, 72, 90 million (JE=1000, JB=9000,
# F=10^12, TOL=1000, MAXSWEEP=4000), split into frozen column chunks, merged, and compared
# record for record by schur_record_compare.py. Every job goes through the HEB-C HTTP-0
# backend (hebc_ym_http0). Missing, truncated, timed-out or failed evidence is
# INCONCLUSIVE; only a fully computed difference is MISMATCH. AGREE on AMBIGUOUS is
# implementation agreement, not a spectral PASS. Integer-only, json=0.
name: HEB-C YM room-lane identity gates (P2, P3)

# Dispatch-only: a rerun is 116 column jobs and is started by hand, never by a push.
on:
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: hebc-ym-room-identity-${{{{ github.ref }}}}
  cancel-in-progress: false

jobs:
  gates:
    name: Rust 1.81 build, clippy -D warnings, comparator controls
    runs-on: ubuntu-latest
    timeout-minutes: 60
    steps:
      - uses: actions/checkout@v4
      - name: Toolchain 1.81
        run: |
          rustup toolchain install 1.81.0 --profile minimal --component clippy
          rustup override set 1.81.0
      - name: Build and lint offline
        working-directory: native/ym
        run: |
          cargo build --release --offline --locked
          cargo clippy --release --all-targets --offline --locked -- -D warnings
      - name: Comparator synthetic controls
        run: python3 native/ym/python/schur_record_compare_controls.py

  p2:
    name: P2 builder identity ${{{{ matrix.l }}}}
    strategy:
      fail-fast: false
      matrix:
        include:
{p2}
    runs-on: ubuntu-latest
    timeout-minutes: 120
    steps:
      - uses: actions/checkout@v4
      - name: Toolchain 1.81
        run: |
          rustup toolchain install 1.81.0 --profile minimal
          rustup override set 1.81.0
      - name: Build offline
        working-directory: native/ym
        run: cargo build --release --offline --locked
      - name: sector + roomident through HTTP-0, each re-executed by verify
        working-directory: native/ym
        env:
          HEBC_YM_FRESH: "1"
          WORKERS: "4"
        run: |
          set -uo pipefail
          B=target/release/hebc_ym_http0; R=$RUNNER_TEMP/root; L="${{{{ matrix.l }}}}"; id=$(echo $L | tr / x)
          mkdir -p out; o=out/p2-$id.hbp; rc=0
          for sp in sector/$L/1/1 roomident/$L/1/1; do
            $B job $R $sp >> $o || rc=1
            $B verify $R $sp >> $o || rc=1
          done
          for d in $R/shards/*/; do sed "s#^#SHARD|$(basename $d)|#" $d/run.hbp >> $o; done
          echo "P2_JOB|L=$L|exit=$rc|json=0" >> $o
          (cd out && sha256sum p2-$id.hbp > p2-$id.sha256)
          exit $rc
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: p2-${{{{ strategy.job-index }}}}
          retention-days: 30
          path: native/ym/out

  p3cols:
    name: P3 ${{{{ matrix.side }}}} t=${{{{ matrix.t }}}} cols ${{{{ matrix.a }}}}:${{{{ matrix.b }}}}
    strategy:
      fail-fast: false
      max-parallel: 20
      matrix:
        include:
{cols}
    runs-on: ubuntu-latest
    timeout-minutes: 350
    steps:
      - uses: actions/checkout@v4
      - name: Toolchain 1.81
        run: |
          rustup toolchain install 1.81.0 --profile minimal
          rustup override set 1.81.0
      - name: Build offline
        working-directory: native/ym
        run: cargo build --release --offline --locked
      - name: Fresh input + column chunk through HTTP-0
        working-directory: native/ym
        env:
          HEBC_YM_FRESH: "1"
          WORKERS: "4"
        run: |
          set -uo pipefail
          B=target/release/hebc_ym_http0; R=$RUNNER_TEMP/root; side=${{{{ matrix.side }}}}; t=${{{{ matrix.t }}}}
          tail="{je}/{jb}/$t/{fdig}/{tol}/${{{{ matrix.a }}}}/${{{{ matrix.b }}}}"
          if [ $side = shell ]; then inp=sector/3/3/1/1; sp=countcols/3/3/1/1/$tail; else inp=roombuild/3/3/1/1; sp=roomcountcols/3/3/1/1/$tail; fi
          mkdir -p out/shards; o=out/job.hbp
          $B job $R $inp > $o && $B job $R $sp >> $o; rc=$?
          echo "P3_COLS_JOB|side=$side|t_milli=$t|cols=${{{{ matrix.a }}}}:${{{{ matrix.b }}}}|exit=$rc|json=0" >> $o
          cp -r $R/shards/[a-z]* out/shards/ 2>/dev/null || true
          exit $rc
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: p3-${{{{ matrix.side }}}}-${{{{ matrix.t }}}}-${{{{ matrix.a }}}}
          retention-days: 30
          path: native/ym/out

  p3merge:
    name: P3 merge ${{{{ matrix.side }}}} t=${{{{ matrix.t }}}}
    needs: [p3cols]
    if: always()
    strategy:
      fail-fast: false
      matrix:
        include:
{merges}
    runs-on: ubuntu-latest
    timeout-minutes: 350
    steps:
      - uses: actions/checkout@v4
      - name: Toolchain 1.81
        run: |
          rustup toolchain install 1.81.0 --profile minimal
          rustup override set 1.81.0
      - name: Build offline
        working-directory: native/ym
        run: cargo build --release --offline --locked
      - uses: actions/download-artifact@v4
        with:
          pattern: p3-${{{{ matrix.side }}}}-${{{{ matrix.t }}}}-*
          path: chunks
      - name: All chunks present, fresh input, merge through HTTP-0, evidence file
        env:
          HEBC_YM_FRESH: "1"
          WORKERS: "4"
        run: |
          set -uo pipefail
          B=native/ym/target/release/hebc_ym_http0; R=$RUNNER_TEMP/root; side=${{{{ matrix.side }}}}; t=${{{{ matrix.t }}}}
          mkdir -p out; ev=out/$side-$t.hbp; : > $ev
          fail() {{ echo "SHELL_SCHUR|result=FAIL|reason=$1|json=0" >> $ev; echo "P3_MERGE|side=$side|t_milli=$t|result=FAIL|reason=$1|json=0" >> $ev; }}
          if [ $side = shell ]; then inp=sector/3/3/1/1; cb=countcols; mk=countmerge; cid=count; else inp=roombuild/3/3/1/1; cb=roomcountcols; mk=roomcountmerge; cid=roomcount; fi
          n=$(ls -d chunks/*/shards/${{cb}}_3_3_1_1_{je}_{jb}_${{t}}_* 2>/dev/null | wc -l)
          echo "P3_MERGE_INPUTS|side=$side|t_milli=$t|chunks_returned=$n|chunks_expected=${{{{ matrix.s }}}}|json=0" >> $ev
          if [ "$n" != "${{{{ matrix.s }}}}" ]; then fail chunks_missing; else
            dir=$R/scol/${{cid}}_3_3_1_1_{je}_{jb}_${{t}}_{fdig}_{tol}; mkdir -p $dir
            cp -r chunks/*/shards/${{cb}}_3_3_1_1_{je}_{jb}_${{t}}_* $dir/
            for d in $dir/*/; do cat $d/run.hbp >> $ev; sed "s#^#RAW_MEASURE|$(basename $d)|#" $d/run.measure >> out/measure.hbp; done
            if $B job $R $inp > out/input.hbp && $B job $R $mk/3/3/1/1/{je}/{jb}/$t/{fdig}/{tol} > out/merge.hbp; then
              m=$R/shards/${{mk}}_3_3_1_1_{je}_{jb}_${{t}}_{fdig}_{tol}
              cat $m/run.hbp >> $ev; sed "s#^#RAW_MEASURE|$(basename $m)|#" $m/run.measure >> out/measure.hbp
              grep -q "^SHELL_SCHUR|.*|core=${{{{ matrix.core }}}}|" $m/run.hbp || fail core_not_frozen_value
            else fail merge_job_failed; cat out/merge.hbp >> $ev 2>/dev/null || true; fi
          fi
          (cd out && sha256sum $side-$t.hbp > $side-$t.sha256)
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: p3m-${{{{ matrix.side }}}}-${{{{ matrix.t }}}}
          retention-days: 30
          path: out

  compare:
    name: P2 check, P3 record comparison, receipt
    needs: [gates, p2, p3merge]
    if: always()
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/download-artifact@v4
        with:
          path: ev
      - name: Compare and seal
        run: |
          # GitHub runs this as bash -e; nonzero comparator exits (MISMATCH = 2) are results, not errors
          set +e
          set -uo pipefail
          o=HEBC-YM-ROOM-IDENTITY-CI.hbp
          echo "ROOM_IDENTITY_CI|run=$GITHUB_RUN_ID|commit=$GITHUB_SHA|gates=${{{{ needs.gates.result }}}}|p2_jobs=${{{{ needs.p2.result }}}}|p3_merges=${{{{ needs.p3merge.result }}}}|cols_jobs_expected={ncols}|json=0" > $o
          p2ok=1
          for L in 2x3 2x4 3x3; do
            f=$(ls ev/p2-*/p2-$L.hbp 2>/dev/null | head -1)
            if [ -n "$f" ] && (cd $(dirname $f) && sha256sum -c --quiet p2-$L.sha256) && [ "$(grep -c '^HEBC_YM|result=PASS|action=verify|' $f)" = 2 ] && [ "$(grep -c "^SHARD|roomident_[0-9_]*|ROOM_IDENTITY|.*|identical=1|" $f)" = 1 ]; then
              grep "^SHARD|roomident_[0-9_]*|ROOM_IDENTITY|" $f >> $o; echo "P2|L=$L|result=PASS|json=0" >> $o
            else p2ok=0; echo "P2|L=$L|result=INCONCLUSIVE_OR_FAIL|json=0" >> $o; [ -n "$f" ] && grep "|ROOM_IDENTITY|" $f >> $o; fi
          done
          args=""
          for t in 60000000 72000000 90000000; do
            for s in shell room; do (cd ev/p3m-$s-$t 2>/dev/null && sha256sum -c --quiet $s-$t.sha256) || echo "P3_EVIDENCE|side=$s|t_milli=$t|sha256_check=FAIL_OR_MISSING|json=0" >> $o; done
            args="$args ev/p3m-shell-$t/shell-$t.hbp ev/p3m-room-$t/room-$t.hbp"
          done
          grep -h "^P3_MERGE" ev/p3m-*/*.hbp >> $o || true
          echo "COMPARATOR|version=v2|sha256=$(sha256sum native/ym/python/schur_record_compare.py | cut -c1-64)|json=0" >> $o
          python3 native/ym/python/schur_record_compare.py $args >> $o; v2=$?
          git show {v1}:native/ym/python/schur_record_compare.py > /tmp/cmp_v1.py
          echo "COMPARATOR|version=v1_{v1}|sha256=$(sha256sum /tmp/cmp_v1.py | cut -c1-64)|json=0" >> $o
          python3 /tmp/cmp_v1.py $args | sed 's/^/V1|/' >> $o
          p3=$(grep '^SCHUR_COMPARE_VERDICT|' $o | head -1 | cut -d'|' -f3)
          echo "ROOM_IDENTITY_CI_RESULT|P2=$([ $p2ok = 1 ] && echo PASS || echo INCONCLUSIVE)|P3_v2=$p3|json=0" >> $o
          sha256sum $o > HEBC-YM-ROOM-IDENTITY-CI.sha256
          cat $o
          [ $p2ok = 1 ] && [ $v2 = 0 ]
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: room-identity-receipt
          retention-days: 90
          path: |
            HEBC-YM-ROOM-IDENTITY-CI.hbp
            HEBC-YM-ROOM-IDENTITY-CI.sha256
"""

if __name__ == "__main__":
    main()
