#!/usr/bin/env python3
"""Write a GitRAM streaming workflow: ymstream over MOD residue classes, one
class per cell (WORKERS = all runner cores), fan-in by stream_fanin.py.

Optional EXPECT file: lines "sector states core@t,core@t,..." that the totals
must reproduce exactly (used to validate the stream against stored-matrix
results).

usage: stream_workflow.py LX LY JE JB T1,T2,... MOD NAME OUT [EXPECT]   json=0
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    lx, ly, je, jb, ts, mod, name, out = sys.argv[1:9]
    expect = sys.argv[9] if len(sys.argv) > 9 else ""
    mod = int(mod)
    root = os.path.join(HERE, "..", "..", "..")
    wfrel = os.path.relpath(out, root)
    exrel = os.path.relpath(expect, os.path.join(HERE, "..")) if expect else ""
    inc = "\n".join(f'          - {{r: {r}}}' for r in range(mod))
    check = ""
    if expect:
        check = f'''
          # the stream must reproduce the stored-matrix sector results exactly
          while read -r sec states cores; do
            grep -q "^YMSTREAM_SECTOR_TOTAL|L={lx}x{ly}|sector=$sec|states=$states|" $F.hbp
            for c in $(echo $cores | tr , ' '); do
              t=${{c#*@}}; n=${{c%@*}}
              grep "^YMSTREAM_SECTOR_TOTAL|L={lx}x{ly}|sector=$sec|" $F.hbp | grep -q "[=,]$t:$n:"
            done
            echo "EXPECT|sector=$sec|states=$states|cores=$cores|match=1|json=0" >> $F.hbp
          done < native/ym/{exrel}'''
    y = f'''# GitRAM streaming lane ({name}): ymstream on the {lx}x{ly} lattice, the
# Host8 / SG-RAM method. Every cell streams one residue class of the 6^k
# gauge-fixed configuration space with constant memory; no matrix is stored.
# Records: gauge orbits (against Burnside), per-op fixed-point counts (the
# character formula for every sector's dimension, against the representative
# count), flat states, and diagonal-dominance core rows at each threshold.
# Generated by native/ym/python/stream_workflow.py. Integer-only, json=0.
name: HEB-C YM {name} ({mod} cells)

on:
  workflow_dispatch:
  push:
    branches: [http0-ym-backend-finite-volumes]
    paths: ['{wfrel}']

permissions:
  contents: read

concurrency:
  group: hebc-ym-{name}-${{{{ github.ref }}}}
  cancel-in-progress: false

jobs:
  cell:
    name: Class ${{{{ matrix.r }}}}/{mod}
    strategy:
      fail-fast: false
      max-parallel: 20
      matrix:
        include:
{inc}
    runs-on: ubuntu-latest
    timeout-minutes: 355
    steps:
      - uses: actions/checkout@v4
      - name: Toolchain 1.81
        run: |
          rustup toolchain install 1.81.0 --profile minimal
          rustup override set 1.81.0
      - name: Build offline from vendored sources
        working-directory: native/ym
        run: cargo build --release --offline --locked
      - name: Stream one residue class
        working-directory: native/ym
        run: |
          set -euo pipefail
          mkdir -p out
          o=out/class-${{{{ matrix.r }}}}.hbp
          WORKERS=$(nproc) target/release/ymstream {lx} {ly} {je} {jb} {ts} ${{{{ matrix.r }}}} {mod} | tee $o
          grep -q '^YMSTREAM|' $o
          echo "GITRAM_CELL|class=${{{{ matrix.r }}}}/{mod}|workers=$(nproc)|json=0" >> $o
          (cd out && sha256sum class-${{{{ matrix.r }}}}.hbp > class-${{{{ matrix.r }}}}.sha256)
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: class-${{{{ matrix.r }}}}
          retention-days: 30
          if-no-files-found: error
          path: native/ym/out

  fan-in:
    name: Fan-in, Burnside and character-formula checks, seal
    needs: cell
    if: always()
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@v4
      - uses: actions/download-artifact@v4
        with:
          pattern: class-*
          path: fan-in
          merge-multiple: true
      - name: Check and seal
        run: |
          set -euo pipefail
          F=HEBC-YM-{name.upper()}
          (cd fan-in && sha256sum -c class-*.sha256)
          cat fan-in/class-*.hbp > $F.hbp
          python3 native/ym/python/stream_fanin.py fan-in/class-*.hbp | tee -a $F.hbp
          grep -q '^YMSTREAM_FANIN|.*|result=PASS|' $F.hbp{check}
          echo "GITRAM_SEAL|name={name}|cells={mod}|status=PASS|json=0" >> $F.hbp
          sha256sum $F.hbp > $F.sha256
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: sealed-{name}
          retention-days: 30
          if-no-files-found: error
          path: HEBC-YM-{name.upper()}.*
'''
    open(out, "w").write(y)
    print(f"STREAM_WORKFLOW|name={name}|L={lx}x{ly}|cells={mod}|out={wfrel}|result=PASS|json=0")


if __name__ == "__main__":
    main()
